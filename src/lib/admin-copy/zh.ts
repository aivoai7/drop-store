export type AdminCopyKey = keyof typeof adminZh;

export function at(key: AdminCopyKey, vars?: Record<string, string | number>) {
  const template = adminZh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}
